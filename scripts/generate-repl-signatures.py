#!/usr/bin/env python3
"""Generate REPL hints from LuaLS annotations; never execute the type stub."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src/lua/hollow/ui/widgets/lua_repl/signatures.lua"


def generate(source):
    classes, locals_ = {}, {"hollow": "Hollow"}
    assignments = []
    current, annotations = None, []
    for line in source.splitlines():
        match = re.match(r"---@class (\w+)", line)
        if match:
            current = match[1]
            classes.setdefault(current, {})
        match = re.match(r"---@field (\w+)\??\s+(.+)", line)
        if match and current:
            classes[current][match[1]] = match[2]
        match = re.match(r"local (\w+) = \{", line)
        if match and current:
            locals_[match[1]] = current
        match = re.match(r"(\w+)\.(\w+) = (\w+)$", line)
        if match:
            assignments.append(match.groups())
        if line.startswith("---@param ") or line.startswith("---@return "):
            annotations.append(line)
        elif line.startswith("function "):
            match = re.match(r"function (\w+)\.(\w+)\(([^)]*)\)", line)
            if match and match[1] in locals_:
                params, returns = {}, []
                for annotation in annotations:
                    param = re.match(r"---@param (\w+|\.\.\.)(\??)\s+(.+)", annotation)
                    if param:
                        params[param[1]] = (param[2], param[3])
                    elif annotation.startswith("---@return "):
                        returns.append(annotation[len("---@return "):])
                args = []
                for name in filter(None, map(str.strip, match[3].split(","))):
                    optional, kind = params.get(name, ("", "any"))
                    args.append(name + optional + ": " + kind)
                signature = "fun(" + ", ".join(args) + ")"
                if returns:
                    signature += ": " + ", ".join(returns)
                classes[locals_[match[1]]][match[2]] = signature
            annotations = []
        elif line and not line.startswith("---"):
            annotations = []

    for owner, field, value in assignments:
        if owner in locals_ and value in locals_:
            classes[locals_[owner]][field] = locals_[value]

    signatures = {}

    def visit(class_name, path, ancestors):
        if class_name in ancestors or len(ancestors) > 6:
            return
        for name, kind in classes.get(class_name, {}).items():
            if kind.startswith("fun(") or kind.startswith("fun<"):
                signatures[path + "." + name] = kind
            elif re.fullmatch(r"\w+", kind):
                visit(kind, path + "." + name, ancestors | {class_name})

    visit("Hollow", "hollow", set())
    lines = ["-- Generated by scripts/generate-repl-signatures.py from types/hollow.lua.",
             "-- Do not edit by hand. No runtime dependency on LuaLS or the type stub.",
             "-- stylua: ignore",
             "return {"]
    for path, signature in sorted(signatures.items()):
        lines.append(f"  [{json.dumps(path)}] = {json.dumps(signature, ensure_ascii=False)},")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate((ROOT / "types/hollow.lua").read_text())
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != result:
            raise SystemExit("REPL signatures stale; run python3 scripts/generate-repl-signatures.py")
    else:
        TARGET.write_text(result)
