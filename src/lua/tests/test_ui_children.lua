package.path = "src/lua/?.lua;src/lua/?/init.lua;src/lua/?.lua;" .. package.path
local harness = require("tests.harness")

describe("declarative UI children", function()
  local ui
  local shared

  setup(function()
    ui = harness.boot().hollow.ui
    shared = require("hollow.ui.shared")
  end)

  it("skips booleans and preserves children after holes", function()
    local children = { "a", nil, false, true, "b", 42 }
    assert.equals("ab42", shared.nodes_plain_text(ui.group(children).children))
    local row = ui.row(children)
    assert.equals("ab42", shared.nodes_plain_text(row.children))
    assert.equals(3, #row.children)
    assert.equals("42", row.children[3].text)
    assert.same({}, ui.group({ nil, false, true }).children)
  end)

  it("flattens deep fragments in depth-first order", function()
    local span = ui.span("b")
    local group = ui.group({ "a", { false, { span, { "c", nil, "d" } } }, "e" })
    assert.equals("abcde", shared.nodes_plain_text(group.children))
    assert.equals(span, group.children[2])
  end)

  it("keeps shorthand as a styled leaf", function()
    local row = ui.row({ { "x", fg = "#123456" }, { "a", "b" } })
    assert.equals(3, #row.children)
    assert.equals("x", row.children[1].text)
    assert.equals("#123456", row.children[1].style.fg)
    assert.equals("xab", shared.nodes_plain_text(row.children))
  end)

  it("does not mistake a sparse string fragment for shorthand", function()
    assert.is_false(shared.is_text_shorthand({ "a", nil, "c" }))
    assert.equals("ac", shared.nodes_plain_text({ { "a", nil, "c" } }))
  end)

  it("splices nested columns and row fragments across holes", function()
    local first = ui.row({ "first", "!" })
    local second = ui.row({ "second", "!" })
    local third = ui.divider("#123456")
    local column = ui.column({ first, nil, false, true, { ui.column({ second }), { third } } })
    assert.same({ first, second, third }, column.children)
    assert.same({}, ui.column({ false, true }).children)
  end)

  it("rejects wrong-kind inline children with container and index", function()
    assert.has_error(function()
      ui.group({ "ok", ui.row({}) })
    end, 'hollow.ui.group(): unexpected "row" node at child 2')
    assert.has_error(function()
      ui.row({ "ok", ui.column({}) })
    end, 'hollow.ui.row(): unexpected "column" node at child 2')
    assert.has_error(function()
      ui.group({ function() end })
    end, 'hollow.ui.group(): unexpected "function" node at child 1')
  end)

  it("rejects inline children in columns with container and index", function()
    assert.has_error(function()
      ui.column({ ui.row({}), ui.span("wrong") })
    end, 'hollow.ui.column(): unexpected "span" node at child 2')
    assert.has_error(function()
      ui.column({ "wrong" })
    end, 'hollow.ui.column(): unexpected "string" node at child 1')
  end)

  it("keeps the row list guard and widget top-level return strict", function()
    assert.has_error(function()
      ui.row(ui.span("bare"))
    end)
    assert.has_error(function()
      ui.row({ "bare", fg = "#123456" })
    end)
    assert.has_error(function()
      shared.normalize_widget_rows({ ui.row({}) })
    end)
  end)

  it("normalizes loose input leniently without rendering booleans", function()
    assert.same({}, shared.normalize_inline_nodes(nil))
    assert.same({}, shared.normalize_inline_nodes(false))
    assert.same({}, shared.normalize_inline_nodes(true))
    assert.same({}, shared.normalize_inline_nodes({}))
    assert.equals("12", shared.normalize_inline_nodes(12)[1].text)
    local wrong = ui.row({})
    assert.equals(tostring(wrong), shared.normalize_inline_nodes(wrong)[1].text)
    assert.equals("ac", shared.nodes_plain_text({ "a", nil, { false, "c" } }))
  end)
end)
